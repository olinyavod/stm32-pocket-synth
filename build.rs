//! Generates the LED sine LUT at compile time so it lives in Flash (.rodata).
//! Audio for the chiptune synth doesn't need an LUT — the PWM hardware itself
//! oscillates at the note frequency.

use std::f32::consts::PI;
use std::fs::write;
use std::path::PathBuf;

const TIMER_CLK_HZ: u32 = 16_000_000;

// LED breathing on TIM1_CH1 (PA8).
const LED_PWM_FREQ_HZ: u32 = 1_000;
const LED_LUT_LEN: usize = 2048;
const LED_GAMMA: f32 = 2.2;

fn psc_arr(timer_clk: u32, freq_hz: u32) -> (u32, u16) {
    let ticks = timer_clk / freq_hz;
    let psc = (ticks - 1) / 65_536;
    let divide_by = ticks / (psc + 1);
    (psc, divide_by as u16)
}

fn main() {
    let (_, led_top) = psc_arr(TIMER_CLK_HZ, LED_PWM_FREQ_HZ);

    let mut s = String::from("// AUTO-GENERATED by build.rs. Do not edit.\n\n");
    s.push_str(&format!("pub const LED_LUT_LEN: usize = {};\n", LED_LUT_LEN));
    s.push_str(&format!("pub const LED_PWM_FREQ_HZ: u32 = {};\n", LED_PWM_FREQ_HZ));
    s.push_str(&format!("pub const LED_PWM_TOP: u16 = {};\n\n", led_top));
    s.push_str("pub static LED_LUT: [u16; LED_LUT_LEN] = [\n");

    for i in 0..LED_LUT_LEN {
        let phase = i as f32 * 2.0 * PI / LED_LUT_LEN as f32;
        let normalized = (phase.sin() + 1.0) * 0.5;
        let perceptual = normalized.powf(LED_GAMMA);
        let duty = (perceptual * led_top as f32) as u16;
        if i % 8 == 0 {
            s.push_str("    ");
        }
        s.push_str(&format!("{}, ", duty));
        if i % 8 == 7 {
            s.push('\n');
        }
    }
    s.push_str("];\n");

    let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR not set");
    write(PathBuf::from(out_dir).join("lut.rs"), s).expect("failed to write lut.rs");

    println!("cargo:rerun-if-changed=build.rs");
}
